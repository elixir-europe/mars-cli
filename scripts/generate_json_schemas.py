"""Generate the MARS JSON schemas from the mars-cli pydantic models.

Writes two files (default: MARS/schemas):

- isa_json.schema.json: JSON Schema for an ISA-JSON investigation.
- isa_json_schema_with_validators.json: the same schema plus the custom
  validators the models run on top of it. The MARS docs site renders this file.

Usage:
    uv run python scripts/generate_json_schemas.py [--output-dir DIR]
"""

import argparse
import inspect
import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from mars_lib.models import isa_json
from mars_lib.models.isa_json import Investigation

DEFAULT_OUTPUT_DIR = Path(__file__).resolve().parents[1] / "MARS" / "schemas"
GENERATED_BY = (
    "Generated by mars-cli scripts/generate_json_schemas.py from "
    "mars_lib/models/isa_json.py. Do not edit by hand."
)


def isa_json_schema() -> dict[str, Any]:
    """JSON Schema for an investigation, the root of an ISA-JSON file.

    Investigation stays in $defs, next to the other models, and the root
    points at it: the docs site renders one table per entry in $defs.
    """
    _, definitions = models_json_schema([(Investigation, "validation")])
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$comment": GENERATED_BY,
        "title": "MARS ISA-JSON",
        "$ref": "#/$defs/Investigation",
        **definitions,
    }


def custom_validators() -> dict[str, dict[str, Any]]:
    """The validators the models apply on top of the JSON Schema."""
    models = [
        obj
        for obj in vars(isa_json).values()
        if inspect.isclass(obj)
        and issubclass(obj, BaseModel)
        and obj.__module__ == isa_json.__name__
    ]
    validators = {}
    for model in models:
        decorators = model.__pydantic_decorators__
        for kind in ("field_validators", "model_validators"):
            for name, decorator in getattr(decorators, kind).items():
                func = getattr(decorator.func, "__func__", decorator.func)
                if func.__qualname__ != f"{model.__name__}.{name}":
                    continue  # inherited: listed under the model that defines it
                validators[func.__qualname__] = {
                    "function_name": name,
                    "model": model.__name__,
                    "fields": list(getattr(decorator.info, "fields", ())),
                    "mode": decorator.info.mode,
                    "docstring": inspect.getdoc(func),
                    "module": func.__module__,
                    "source": inspect.getsource(func),
                }
    return dict(sorted(validators.items()))


def build_schema_files() -> dict[str, dict[str, Any]]:
    schema = isa_json_schema()
    return {
        "isa_json.schema.json": schema,
        "isa_json_schema_with_validators.json": {
            "schema": schema,
            "validators": custom_validators(),
        },
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    output_dir = parser.parse_args().output_dir

    output_dir.mkdir(parents=True, exist_ok=True)
    for name, content in build_schema_files().items():
        path = output_dir / name
        path.write_text(json.dumps(content, indent=2, ensure_ascii=False) + "\n")
        print(f"Wrote {path}")


if __name__ == "__main__":
    main()
